    /// Check if this stat type uses a string value instead of integer.
    pub fn is_string_stat(id: u8) -> bool {
        matches!(
            id,
            6   // EXP_STAT
            | 31  // NAME_STAT
            | 38  // ACCOUNT_ID_STAT
            | 54  // OWNER_ACCOUNT_ID_STAT
            | 62  // GUILD_NAME_STAT
            | 71  // MATERIAL_STAT
            | 72  // MATERIAL_CAP_STAT
            | 78  // Unknown string stat observed on player objects
            | 80  // UNIQUE_DATA_STRING
            | 82  // PET_NAME_STAT
            | 115 // GRAVE_ACCOUNT_ID
            | 121 // MODIFIERS_STAT
            | 127 // DUST_STAT
            | 128 // CRUCIBLE_STAT
            | 147 // DUST_AMOUNT_STAT
            | 155 // BloodRitualStat
        )
    }
