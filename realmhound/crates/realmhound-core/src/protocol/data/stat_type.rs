#[cfg(test)]
mod tests {
    use super::StatType;

    #[test]
    fn condition_new_is_stat_id_69() {
        // The current protocol carries ConditionNew (Cursed/Exposed/Petrified)
        // on id 69; the legacy id 96 is no longer sent.
        assert_eq!(StatType::ConditionNew as u8, 69);
        assert_eq!(StatType::from_id(69), StatType::ConditionNew);
        assert_eq!(StatType::from_id(96), StatType::Unknown);
    }
}
